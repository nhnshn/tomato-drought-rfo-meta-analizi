#!/usr/bin/env python3
"""Snapshot code, input and output hashes for a NEW run; never rewrites old evidence.

The initial snapshot includes primary and optional external inputs when present.
Sealing fails if the input or code snapshots changed after the initial snapshot.
Optional targets must be run explicitly; see README.  Hash matches do not prove
biological validity or that pre-existing outputs were generated by this run.
"""
import argparse
import hashlib
import json
import os
import platform
import subprocess
import sys
from datetime import datetime, timezone
from importlib import metadata
from pathlib import Path

TRACKED_DIRS = ('scripts', 'config', 'envs')
OUTPUT_DIRS = ('de', 'de_leaf_primary', 'de_leaf_baseline', 'de_leaf_unresolved',
               'meta', 'meta_baseline', 'meta_unresolved', 'meta_subgroup_method',
               'genotype_results', 'meta_tissue', 'meta_rotation', 'meta_calibration', 'meta_sensitivity',
               'rep/out', 'figures', 'logs')
OUTPUT_SUFFIXES = ('.csv', '.tsv', '.json', '.gz', '.png', '.log')



def git_commit():
    """Record the commit the run was made from, so the manifest anchors to a code
    revision and not only to content hashes. 'untracked' when the tree is not a
    repository; '<sha>-dirty' when it is but has uncommitted changes."""
    try:
        sha = subprocess.run(["git", "rev-parse", "--short", "HEAD"],
                             capture_output=True, text=True, timeout=10)
        if sha.returncode != 0:
            return "untracked"
        dirty = subprocess.run(["git", "status", "--porcelain"],
                               capture_output=True, text=True, timeout=10).stdout.strip()
        return sha.stdout.strip() + ("-dirty" if dirty else "")
    except Exception:
        return "untracked"


def utc():
    return datetime.now(timezone.utc).isoformat(timespec='seconds')


def sha256(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return {'sha256': h.hexdigest(), 'bytes': os.path.getsize(path)}


def files_for(paths):
    found = {}
    for value in paths:
        p = Path(value)
        if p.is_file():
            found[str(p)] = sha256(p)
        elif p.is_dir():
            for f in sorted(p.rglob('*')):
                if f.is_file() and '__pycache__' not in f.parts and f.suffix != '.pyc':
                    found[str(f)] = sha256(f)
    return dict(sorted(found.items()))


def code_snapshot():
    return files_for((*TRACKED_DIRS, 'Makefile'))


def input_snapshot(args):
    paths = ([args.inputs] if args.inputs else []) + (args.extra_inputs or [])
    return files_for(paths)


def output_snapshot():
    found = {}
    for root in OUTPUT_DIRS:
        p = Path(root)
        if not p.is_dir():
            continue
        for f in sorted(p.rglob('*')):
            if not f.is_file() or not str(f).endswith(OUTPUT_SUFFIXES):
                continue
            # Avoid hashing a manifest into itself and a log that changes while sealing.
            if f.name in ('RUN_MANIFEST.json', 'seal.log'):
                continue
            found[str(f)] = sha256(f)
    return dict(sorted(found.items()))


def python_versions():
    versions = {}
    for name in ('numpy', 'pandas', 'scipy', 'statsmodels', 'pydeseq2', 'pymare', 'matplotlib'):
        try:
            versions[name] = metadata.version(name)
        except metadata.PackageNotFoundError:
            versions[name] = 'not installed'
    return versions


def r_versions(executable):
    expr = ('cat(R.version.string,"\\n"); '
            'for(p in c("limma","edgeR")) '
            'cat(p, if(requireNamespace(p,quietly=TRUE)) as.character(packageVersion(p)) '
            'else "not installed", "\\n")')
    try:
        r = subprocess.run([executable, '-e', expr], capture_output=True, text=True, timeout=30)
        return {'executable': executable, 'exit_code': r.returncode,
                'stdout': r.stdout.strip(), 'stderr': r.stderr.strip()}
    except (OSError, subprocess.TimeoutExpired) as e:
        return {'executable': executable, 'error': str(e)}


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--out', required=True)
    ap.add_argument('--note', default='')
    ap.add_argument('--inputs', default=None)
    ap.add_argument('--extra-inputs', nargs='*', default=[])
    ap.add_argument('--rscript', default='Rscript')
    ap.add_argument('--seal', action='store_true')
    ap.add_argument('--required-output', action='append', default=[])
    args = ap.parse_args()
    target = Path(args.out)
    target.parent.mkdir(parents=True, exist_ok=True)
    if args.seal:
        if not target.is_file():
            raise SystemExit('Cannot seal: run-start manifest is missing')
        data = json.loads(target.read_text())
        if data.get('files') != code_snapshot():
            raise SystemExit('Cannot seal: tracked code/configuration changed after run start')
        if data.get('inputs') != input_snapshot(args):
            raise SystemExit('Cannot seal: input files changed after run start')
        data['outputs'] = output_snapshot()
        missing = [p for p in args.required_output if p not in data['outputs']]
        if missing:
            raise SystemExit('Cannot seal: required outputs missing: ' + ', '.join(missing))
        data['n_outputs'] = len(data['outputs'])
        data['sealed_utc'] = utc()
        target.write_text(json.dumps(data, indent=2, sort_keys=True) + '\n')
        print(f"sealed {data['n_outputs']} output files at {data['sealed_utc']}")
    else:
        inputs = input_snapshot(args)
        if args.inputs and not any(k.startswith(str(Path(args.inputs)) + os.sep) for k in inputs):
            raise SystemExit('No input files found in the required primary input directory')
        data = {'run_started_utc': utc(), 'git_commit': git_commit(), 'note': args.note, 'python': sys.version.split()[0],
                'platform': platform.platform(), 'cwd': os.getcwd(),
                'python_packages': python_versions(), 'r_packages': r_versions(args.rscript),
                'files': code_snapshot(), 'inputs': inputs,
                'input_paths_requested': ([args.inputs] if args.inputs else []) + args.extra_inputs}
        data['n_tracked_files'] = len(data['files'])
        data['n_inputs'] = len(data['inputs'])
        target.write_text(json.dumps(data, indent=2, sort_keys=True) + '\n')
        print(f"started {data['run_started_utc']}; {data['n_tracked_files']} code/config files, {data['n_inputs']} input files")


if __name__ == '__main__':
    main()
